var zstdMagic = []byte{0x28, 0xb5, 0x2f, 0xfd}

type HarvestStats struct {
	Files, Skipped, Partial, Records, Deliveries int
	Domains                                      []string
}

func runHarvest(args []string, out io.Writer) error {
	fl := flag.NewFlagSet("harvest", flag.ContinueOnError)
	logs := fl.String("kumo-logs", "/var/log/kumomta", "KumoMTA log directory")
	days := fl.Int("days", 90, "look-back window in days")
	dst := fl.String("out", "/var/lib/typo-guard/delivered.txt", "output file")
	if err := fl.Parse(args); err != nil {
		return err
	}
	if *days <= 0 {
		return errors.New("harvest: -days must be > 0")
	}
	start := time.Now()
	st, err := Harvest(*logs, time.Now().Add(-time.Duration(*days)*24*time.Hour))
	if err != nil {
		return fmt.Errorf("harvest: %w", err)
	}
	if len(st.Domains) == 0 {
		fmt.Fprintf(out, "harvest: %d files read, no delivered domains found in %s, %s left unchanged\n", st.Files, *logs, *dst)
		return nil
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# generated by typo-guard harvest from %s, %d days, %s\n", *logs, *days, time.Now().UTC().Format(time.RFC3339))
	for _, d := range st.Domains {
		buf.WriteString(d)
		buf.WriteByte('\n')
	}
	if err := writeFileAtomic(*dst, buf.Bytes()); err != nil {
		return fmt.Errorf("harvest: %w", err)
	}
	fmt.Fprintf(out, "harvest: %d files read (%d skipped by age, %d partial), %d records, %d deliveries, %d domains written to %s in %s\n",
		st.Files, st.Skipped, st.Partial, st.Records, st.Deliveries, len(st.Domains), *dst, time.Since(start).Round(time.Millisecond))
	return nil
}

// Harvest collects recipient domains of Delivery records newer than since.
func Harvest(dir string, since time.Time) (*HarvestStats, error) {
	st := &HarvestStats{}
	domains := map[string]struct{}{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.Type().IsRegular() {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return nil
		}
		if info.ModTime().Before(since) {
			st.Skipped++
			return nil
		}
		st.Files++
		if partial := harvestFile(path, since, domains, st); partial {
			st.Partial++
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for d := range domains {
		st.Domains = append(st.Domains, d)
	}
	sort.Strings(st.Domains)
	return st, nil
}

type kumoRecord struct {
	Type      string          `json:"type"`
	Recipient json.RawMessage `json:"recipient"`
	Timestamp float64         `json:"timestamp"`
}

// harvestFile reads one segment; it returns true when the stream ended early.
func harvestFile(path string, since time.Time, domains map[string]struct{}, st *HarvestStats) bool {
	f, err := os.Open(path)
	if err != nil {
		return true
	}
	defer f.Close()
	br := bufio.NewReaderSize(f, 256*1024)
	var r io.Reader = br
	if magic, _ := br.Peek(4); bytes.Equal(magic, zstdMagic) {
		dec, err := zstd.NewReader(br, zstd.WithDecoderConcurrency(1), zstd.WithDecoderMaxMemory(1<<30))
		if err != nil {
			return true
		}
		defer dec.Close()
		r = dec
	}
	cutoff := float64(since.Unix())
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64*1024), 16*1024*1024)
	for sc.Scan() {
		line := sc.Bytes()
		st.Records++
		if !bytes.Contains(line, []byte(`"Delivery"`)) {
			continue
		}
		var rec kumoRecord
		if json.Unmarshal(line, &rec) != nil || rec.Type != "Delivery" || rec.Timestamp < cutoff {
			continue
		}
		st.Deliveries++
		for _, rcpt := range recipients(rec.Recipient) {
			if d := recipientDomain(rcpt); d != "" && !strings.ContainsAny(d, " \t\"<>") {
				domains[d] = struct{}{}
			}
		}
	}
	// A truncated final frame (segment still being written) surfaces here.
	return sc.Err() != nil
}

// recipients accepts a string or an array of strings.
func recipients(raw json.RawMessage) []string {
	var one string
	if json.Unmarshal(raw, &one) == nil {
		return []string{one}
	}
	var many []string
	json.Unmarshal(raw, &many)
	return many
}
